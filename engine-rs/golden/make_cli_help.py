def cell_widths() -> None:
    table = load_cell_table("latest")
    rows = "".join(f"    (0x{a:04X}, 0x{b:04X}, {w}),\n" for a, b, w in table.widths)
    narrow = "".join(f"    0x{ord(c):04X},\n" for c in sorted(table.narrow_to_wide))
    from importlib.metadata import version

    text = (f"//! Generated by `engine-rs/golden/make_cli_help.py` from rich {version('rich')} "
            f"(`rich._unicode_data`, Unicode {table.unicode_version}). Do not edit.\n\n"
            "/// `(first, last, cells)` ranges of code points that are not one cell wide, sorted.\n"
            "#[rustfmt::skip]\n"
            f"pub(crate) const WIDTHS: &[(u32, u32, u8)] = &[\n{rows}];\n\n"
            "/// Characters a following U+FE0F (variation selector 16) widens from one cell to two, sorted.\n"
            "#[rustfmt::skip]\n"
            f"pub(crate) const NARROW_TO_WIDE: &[u32] = &[\n{narrow}];\n")
    (ROOT / "crates/tellfold-cli/src/term/cell_widths.rs").write_text(text, encoding="utf-8")



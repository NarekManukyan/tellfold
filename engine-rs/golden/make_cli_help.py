def build_table(spec: dict) -> Table:
    box_name = spec.get("box", "HEAVY_HEAD")
    table = Table(title=spec.get("title"), title_justify=spec.get("title_justify", "left"),
                  box=getattr(box, box_name) if box_name else None, expand=spec.get("expand", False),
                  show_header=spec.get("show_header", True), show_edge=spec.get("show_edge", True),
                  pad_edge=spec.get("pad_edge", True), collapse_padding=spec.get("collapse_padding", False),
                  padding=tuple(spec.get("padding", [0, 1, 0, 1])))
    for col in spec["columns"]:
        table.add_column(col["header"], justify=col.get("justify", "left"), overflow=col.get("overflow", "ellipsis"),
                         width=col.get("width"), min_width=col.get("min_width"), max_width=col.get("max_width"),
                         ratio=col.get("ratio"), no_wrap=col.get("no_wrap", False))
    for row in spec["rows"]:
        table.add_row(*[Text(cell) for cell in row])
    return table



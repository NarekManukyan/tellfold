def param_help(param: _click.Parameter, ctx: _click.Context) -> dict:
    """The strings `typer.rich_utils._print_options_panel` and `_get_parameter_help` derive from one parameter."""
    opt_long, opt_short, sec_long, sec_short = [], [], [], []
    metavar_name = None
    metavar_type = None
    metavar_str = param.make_metavar(ctx=ctx)
    if isinstance(param, TyperArgument):
        metavar_name = param.metavar if param.metavar is not None else (param.name or "")
    if isinstance(param, TyperOption):
        metavar_type = metavar_str
    elif isinstance(param, TyperArgument):
        metavar_type = param.type.get_metavar(param=param, ctx=ctx)
        if metavar_type is None:
            metavar_type = f"<{param.type.name}>"
    for opt in param.opts:
        if "--" in opt:
            opt_long.append(opt)
        elif metavar_name:
            opt_short.append(metavar_name)
        else:
            opt_short.append(opt)
    for opt in param.secondary_opts:
        if "--" in opt:
            sec_long.append(opt)
        elif metavar_name:
            sec_short.append(metavar_name)
        else:
            sec_short.append(opt)
    types = ""
    if metavar_type and "bool" not in metavar_type.lower():
        types += metavar_type
    if (isinstance(param.type, click_types._NumberRangeBase) and isinstance(param, TyperOption)
            and not (param.count and param.type.min == 0 and param.type.max is None)):
        range_str = param.type._describe_range()
        if range_str:
            types += f" [{range_str}]"

    envvar = getattr(param, "envvar", None)
    if envvar is None and (getattr(param, "allow_from_autoenv", None)
                           and getattr(ctx, "auto_envvar_prefix", None) is not None and param.name is not None):
        envvar = f"{ctx.auto_envvar_prefix}_{param.name.upper()}"
    shown_envvar = None
    if envvar and getattr(param, "show_envvar", None):
        shown_envvar = envvar if isinstance(envvar, str) else ", ".join(str(d) for d in envvar)

    default = None
    if isinstance(param, (TyperOption, TyperArgument)):
        default_value = param._extract_default_help_str(ctx=ctx)
        show_default_is_str = isinstance(param.show_default, str)
        if show_default_is_str or (default_value is not None and (param.show_default or ctx.show_default)):
            default_str = param._get_default_string(ctx=ctx, show_default_is_str=show_default_is_str,
                                                    default_value=default_value)
            if default_str:
                default = default_str
    return {
        "required": bool(param.required), "long": ",".join(opt_long), "short": ",".join(opt_short),
        "secondary_long": ",".join(sec_long), "secondary_short": ",".join(sec_short), "types": types,
        "help": getattr(param, "help", None) or "", "default": default, "envvar": shown_envvar,
    }


def command_help(obj: _click.Command, ctx: _click.Context) -> dict:
    arguments, options = [], []
    for param in obj.get_params(ctx):
        if getattr(param, "hidden", False):
            continue
        assert not getattr(param, "rich_help_panel", None), "custom help panels are not ported"
        if isinstance(param, TyperArgument):
            arguments.append(param_help(param, ctx))
        elif isinstance(param, TyperOption):
            options.append(param_help(param, ctx))
    commands = []
    if isinstance(obj, TyperGroup):
        for name in obj.list_commands(ctx):
            command = obj.get_command(ctx, name)
            if command and not command.hidden:
                assert not getattr(command, "rich_help_panel", None) and not command.deprecated
                commands.append([command.name or "", command.short_help or command.help or ""])
    assert not obj.deprecated and not obj.epilog
    return {"usage": obj.get_usage(ctx), "help": obj.help or "", "arguments": arguments, "options": options,
            "commands": commands}


def help_fixtures() -> None:
    group = typer.main.get_command(cli.app)
    runner = CliRunner()
    out = []
    root_ctx = _click.Context(group, info_name="tellfold")
    names = [None, *group.list_commands(root_ctx)]
    for name in names:
        if name is None:
            obj, ctx, path = group, root_ctx, []
        else:
            obj = group.get_command(root_ctx, name)
            ctx = _click.Context(obj, info_name=name, parent=root_ctx)
            path = [name]
        data = command_help(obj, ctx)
        assert "\n" not in data["usage"], data["usage"]
        renders = {}
        for width in WIDTHS:
            result = runner.invoke(cli.app, [*path, "--help"], env={"COLUMNS": str(width)}, prog_name="tellfold")
            assert result.exit_code == 0, result.output
            renders[str(width)] = result.stdout
        out.append({"command": name or "", "data": data, "renders": renders})
    # The CliRunner path must print what the installed CLI prints into a pipe.
    real = subprocess.run([sys.executable, "-m", "tellfold", "run", "--help"], capture_output=True, text=True,
                          env={**os.environ, "COLUMNS": "80"}, check=True).stdout
    run_80 = next(c for c in out if c["command"] == "run")["renders"]["80"]
    assert real == run_80, "CliRunner output differs from `tellfold run --help | cat`"
    dump("help.json", out)


def error_fixtures() -> None:
    group = typer.main.get_command(cli.app)
    runner = CliRunner()
    with tempfile.TemporaryDirectory() as tmp:
        seed = Path(tmp) / "seed.md"
        seed.write_text("x", encoding="utf-8")
        cases = [
            ("missing option", ["run", str(seed)]),
            ("out of range", ["run", str(seed), "-q", "why?", "--agents", "1"]),
            ("not an int", ["run", str(seed), "-q", "why?", "--rounds", "many"]),
            ("unknown option", ["doctor", "--bogus"]),
            ("extra argument", ["doctor", "extra"]),
            ("no such command", ["bogus"]),
            ("missing argument", ["agents"]),
            ("missing option value", ["chat", tmp, "--agent"]),
        ]
        out = []
        for label, args in cases:
            try:
                group.main(args=args, prog_name="tellfold", standalone_mode=False)
            except _click.ClickException as e:
                ctx = getattr(e, "ctx", None)  # None for errors raised outside a context: no usage lines then
                data = {"usage": ctx.get_usage() if ctx else "", "command_path": ctx.command_path if ctx else "",
                        "message": e.format_message()}
            else:
                raise AssertionError(f"{label}: no usage error")
            renders = {}
            for width in WIDTHS:
                result = runner.invoke(cli.app, args, env={"COLUMNS": str(width)}, prog_name="tellfold")
                assert result.exit_code == 2, (label, result.output)
                renders[str(width)] = result.stderr.replace(tmp, "<tmp>")
            data["message"] = data["message"].replace(tmp, "<tmp>")
            out.append({"case": label, "data": data, "renders": renders})
    dump("errors.json", out)


